// Gobble Run: The Great Turkey Escape – make.fun entry (Node 22, standard library only)
// A multi-stage side-scrolling turkey escape game where a turkey runs through the farmyard,
// barn, and kitchen to escape becoming Thanksgiving dinner. Features jumping, ducking, dashing,
// a chasing farmer, flying knives, ovens, haybales, pumpkins, corn collectibles, wishbones,
// Web Audio synthesized music and SFX, particle effects, and 3 escalating stages.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'game'), join(out, 'game'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
if (existsSync(join(here, 'screenshots'))) cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });

writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    game_max_files: 993,
    game_max_bytes: 50331648,
    game_path_max_bytes: 1000,
  }),
);
